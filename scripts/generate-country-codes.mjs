import { writeFile } from "node:fs/promises";

import countries from "i18n-iso-countries";
import enLocale from "i18n-iso-countries/langs/en.json" with { type: "json" };

countries.registerLocale(enLocale);

const codes = Object.keys(countries.getAlpha2Codes()).sort();
const englishNames = countries.getNames("en", { select: "official" });

const entries = codes.map((code) => {
  const name = englishNames[code];
  if (typeof name !== "string" || name.trim().length === 0) {
    throw new TypeError(`Missing English country name for ${code}`);
  }
  return { code, name };
});

const generatedSource = `/**
 * Generated by scripts/generate-country-codes.mjs from i18n-iso-countries.
 * Do not edit by hand; run \`pnpm generate:country-codes\`.
 */
export const COUNTRY_CODES = [
${entries.map(({ code }) => `  ${JSON.stringify(code)},`).join("\n")}
] as const;

export type CountryCode = (typeof COUNTRY_CODES)[number];

export const STATIC_COUNTRY_LABEL_MAP: Readonly<Record<string, string>> =
  Object.freeze({
${entries
  .map(({ code, name }) => `    ${JSON.stringify(code)}: ${JSON.stringify(name)},`)
  .join("\n")}
  } satisfies Record<CountryCode, string>);
`;

await writeFile(
  new URL("../src/country-codes.generated.ts", import.meta.url),
  generatedSource,
  "utf8",
);
