#!/usr/bin/env node
/**
 * Generates `src/aroma-descriptors.generated.ts` from the vendored canonical
 * JSON's `aroma_descriptors` row (CEL-1618).
 *
 * Same pattern as `scripts/generate-classifications.mjs` ->
 * `src/classifications.generated.ts`: `getAromaDescriptorFamilies()`
 * (`src/aroma-descriptors.ts`) reads this generated literal instead of the
 * live `src/canonical/reference-data.json` at runtime, so importing it does
 * not pull the full vendored JSON into a consumer's bundle.
 *
 * Reads the already-vendored `src/canonical/reference-data.json` (refresh
 * that first via `pnpm sync-canonical` if the backend row changed) — this
 * script itself never touches the network or a backend checkout.
 *
 * Wired into `pnpm sync-canonical` (`scripts/sync-canonical.mjs` calls this
 * automatically after every sync) and gated by
 * `pnpm check-aroma-descriptors-fresh` (part of `npm test`) so a hand-edit
 * or a forgotten regeneration fails CI loudly instead of silently drifting.
 *
 * Usage:
 *   node scripts/generate-aroma-descriptors.mjs
 *   pnpm generate:aroma-descriptors
 *
 * Do NOT edit `src/aroma-descriptors.generated.ts` by hand.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE_JSON_URL = new URL("../src/canonical/reference-data.json", import.meta.url);
const DEST_TS_URL = new URL("../src/aroma-descriptors.generated.ts", import.meta.url);

async function main() {
  const sourcePath = fileURLToPath(SOURCE_JSON_URL);
  let raw;
  try {
    raw = await readFile(SOURCE_JSON_URL, "utf8");
  } catch (cause) {
    throw new Error(
      `Could not read ${sourcePath}. Run \`pnpm sync-canonical\` first to ` +
        `vendor the backend canonical JSON before generating aroma descriptors.`,
      { cause },
    );
  }

  /** @type {{ data: Array<{ dataId: string; jsonData: unknown }> }} */
  const parsed = JSON.parse(raw);
  const row = parsed?.data?.find?.((r) => r.dataId === "aroma_descriptors");
  if (!row) {
    throw new Error(
      `"aroma_descriptors" row is missing from ${sourcePath}. Re-run ` +
        `\`pnpm sync-canonical\` against a backend commit that still ships this row.`,
    );
  }

  /**
   * @type {{ families: Record<string, { label: string; standardRef: string; terms: Array<{ slug: string; label: string; "x-standard": string; aliases?: string[] }> }> }}
   */
  const jsonData = row.jsonData;

  /** @type {Record<string, { label: string; standardRef: string; terms: Array<{ slug: string; label: string; "x-standard": string; aliases?: string[] }> }>} */
  const families = {};
  for (const familyId of Object.keys(jsonData.families).sort()) {
    const family = jsonData.families[familyId];
    families[familyId] = {
      label: family.label,
      standardRef: family.standardRef,
      terms: family.terms.map((t) => ({
        slug: t.slug,
        label: t.label,
        "x-standard": t["x-standard"],
        ...(t.aliases && t.aliases.length > 0 ? { aliases: t.aliases } : {}),
      })),
    };
  }

  const familyCount = Object.keys(families).length;
  const termCount = Object.values(families).reduce((sum, f) => sum + f.terms.length, 0);

  const generatedSource = `/**
 * Generated by scripts/generate-aroma-descriptors.mjs from the
 * "aroma_descriptors" row of src/canonical/reference-data.json.
 * Do not edit by hand; run \`pnpm generate:aroma-descriptors\` (or
 * \`pnpm sync-canonical\`, which calls it automatically after every sync).
 */
import type { AromaDescriptorFamilies } from "./types.js";

export const CANONICAL_AROMA_DESCRIPTOR_FAMILIES: AromaDescriptorFamilies = ${JSON.stringify(
    families,
    null,
    2,
  )};
`;

  await writeFile(DEST_TS_URL, generatedSource, "utf8");
  console.log(
    `Generated ${familyCount} aroma-descriptor families (${termCount} terms) -> ` +
      `${fileURLToPath(DEST_TS_URL)}`,
  );
}

main().catch((err) => {
  console.error(err.message ?? err);
  process.exitCode = 1;
});
