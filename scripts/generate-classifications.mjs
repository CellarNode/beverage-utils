#!/usr/bin/env node
/**
 * Generates `src/classifications.generated.ts` from the vendored canonical
 * JSON's `beverage_classifications` row (CEL-1604 review fixup, P0-1).
 *
 * Same pattern as `scripts/generate-country-codes.mjs` ->
 * `src/country-codes.generated.ts`: `getCanonicalClassifications()`
 * (`src/classifications.ts`) reads this generated literal instead of the
 * live `src/canonical/reference-data.json` at runtime, so importing it
 * does not pull the 157 KB vendored JSON into a consumer's bundle.
 *
 * Reads the already-vendored `src/canonical/reference-data.json` (refresh
 * that first via `pnpm sync-canonical` if the backend row changed) — this
 * script itself never touches the network or a backend checkout.
 *
 * Wired into `pnpm sync-canonical` (`scripts/sync-canonical.mjs` calls this
 * automatically after every sync) and gated by `pnpm check-classifications-fresh`
 * (part of `npm test`) so a hand-edit or a forgotten regeneration fails CI
 * loudly instead of silently drifting.
 *
 * Usage:
 *   node scripts/generate-classifications.mjs
 *   pnpm generate:classifications
 *
 * Do NOT edit `src/classifications.generated.ts` by hand.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE_JSON_URL = new URL(
  "../src/canonical/reference-data.json",
  import.meta.url,
);
const DEST_TS_URL = new URL(
  "../src/classifications.generated.ts",
  import.meta.url,
);

async function main() {
  const sourcePath = fileURLToPath(SOURCE_JSON_URL);
  let raw;
  try {
    raw = await readFile(SOURCE_JSON_URL, "utf8");
  } catch (cause) {
    throw new Error(
      `Could not read ${sourcePath}. Run \`pnpm sync-canonical\` first to ` +
        `vendor the backend canonical JSON before generating classifications.`,
      { cause },
    );
  }

  /** @type {{ data: Array<{ dataId: string; jsonData: unknown }> }} */
  const parsed = JSON.parse(raw);
  const row = parsed?.data?.find?.((r) => r.dataId === "beverage_classifications");
  if (!row) {
    throw new Error(
      `"beverage_classifications" row is missing from ${sourcePath}. ` +
        `Re-run \`pnpm sync-canonical\` against a backend commit that still ` +
        `ships this row.`,
    );
  }

  /** @type {{ categories: Array<{ id: string; name: string; hsHeading?: string; subtypes: Array<{ id: string; name: string; oivType?: string }> }> }} */
  const jsonData = row.jsonData;

  const categories = jsonData.categories.map((cat) => ({
    id: cat.id,
    name: cat.name,
    hsHeading: cat.hsHeading,
    subtypes: cat.subtypes.map((sub) => ({
      id: sub.id,
      name: sub.name,
      oivType: sub.oivType,
    })),
  }));

  const generatedSource = `/**
 * Generated by scripts/generate-classifications.mjs from the
 * "beverage_classifications" row of src/canonical/reference-data.json.
 * Do not edit by hand; run \`pnpm generate:classifications\` (or
 * \`pnpm sync-canonical\`, which calls it automatically after every sync).
 */
import type { BeverageClassification } from "./types.js";

export const CANONICAL_CLASSIFICATIONS: BeverageClassification = ${JSON.stringify(
    { categories },
    null,
    2,
  )};
`;

  await writeFile(DEST_TS_URL, generatedSource, "utf8");
  console.log(
    `Generated ${categories.length} canonical classification categories -> ` +
      `${fileURLToPath(DEST_TS_URL)}`,
  );
}

main().catch((err) => {
  console.error(err.message ?? err);
  process.exitCode = 1;
});
